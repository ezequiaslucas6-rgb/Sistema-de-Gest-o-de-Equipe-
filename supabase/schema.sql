-- Estrutura do banco no Supabase (projeto compartilhado com o sistema da frota).
-- Tudo do sistema de escalas usa o prefixo escala_ e não altera nenhuma outra tabela.
-- Aplicado em 21/10/2026 pelas migrações escala_tecnica_tabelas, escala_tecnica_funcao_membro,
-- escala_tecnica_politicas e escala_tecnica_rodizio_plantao_sql.

create type public.escala_sector as enum ('suporte', 'infraestrutura');
create type public.escala_scale_type as enum ('6x1', '5x2');
create type public.escala_absence_kind as enum ('ferias', 'atestado', 'folga_extra', 'treinamento', 'outro');
create type public.escala_holiday_kind as enum ('nacional', 'estadual', 'municipal', 'ponto_facultativo');

-- Quem pode usar o sistema (e-mails de usuários do Supabase Auth)
create table public.escala_usuarios (
  email text primary key check (email = lower(email)),
  created_at timestamptz not null default now()
);

create table public.escala_teams (
  id bigint generated by default as identity primary key,
  name text not null,
  code text not null,
  sector public.escala_sector not null,
  vehicle text,
  notes text,
  created_at timestamptz not null default now()
);

create table public.escala_technicians (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  role text,
  team_id bigint references public.escala_teams(id) on delete set null,
  created_at timestamptz not null default now()
);
create index escala_technicians_team_idx on public.escala_technicians(team_id);

create table public.escala_absences (
  id bigint generated by default as identity primary key,
  technician_id bigint not null references public.escala_technicians(id) on delete cascade,
  start_date text not null check (start_date ~ '^\d{4}-\d{2}-\d{2}$'),
  end_date text not null check (end_date ~ '^\d{4}-\d{2}-\d{2}$'),
  kind public.escala_absence_kind not null,
  notes text,
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);
create index escala_absences_tech_idx on public.escala_absences(technician_id);

create table public.escala_sector_settings (
  sector public.escala_sector primary key,
  min_coverage jsonb not null,
  max_consecutive integer not null default 6,
  hours_six_one numeric not null default 8,
  hours_six_one_saturday numeric not null default 4,
  hours_five_two numeric not null default 8.8,
  shift_start text not null default '08:00',
  shift_end text not null default '17:48',
  on_call_teams integer not null default 1,
  on_call_saturday text not null default '14:00-18:00',
  on_call_sunday text not null default '08:00-12:00,14:00-18:00'
);

create table public.escala_schedule_patterns (
  id bigint generated by default as identity primary key,
  sector public.escala_sector not null,
  scale_type public.escala_scale_type not null,
  name text not null,
  start_date text not null check (start_date ~ '^\d{4}-\d{2}-\d{2}$'),
  cycle_weeks integer not null check (cycle_weeks > 0),
  days_off jsonb not null,
  created_at timestamptz not null default now(),
  unique (sector, start_date)
);

create table public.escala_on_call_shifts (
  id bigint generated by default as identity primary key,
  team_id bigint not null references public.escala_teams(id) on delete cascade,
  weekend_start text not null check (weekend_start ~ '^\d{4}-\d{2}-\d{2}$'),
  comp_dates jsonb not null default '[]'::jsonb,
  notes text,
  created_at timestamptz not null default now(),
  unique (team_id, weekend_start)
);
create index escala_on_call_weekend_idx on public.escala_on_call_shifts(weekend_start);

create table public.escala_holidays (
  id bigint generated by default as identity primary key,
  date text not null unique check (date ~ '^\d{4}-\d{2}-\d{2}$'),
  name text not null,
  kind public.escala_holiday_kind not null,
  day_off boolean not null default true,
  on_call_team_ids jsonb not null default '[]'::jsonb,
  on_call_hours text not null default '08:00-12:00,14:00-18:00',
  comp_date text check (comp_date ~ '^\d{4}-\d{2}-\d{2}$'),
  created_at timestamptz not null default now()
);

-- Acesso: só usuários autenticados cujo e-mail está em escala_usuarios
create or replace function public.escala_is_member()
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select exists (
    select 1 from public.escala_usuarios u
    where u.email = lower(coalesce((select auth.jwt()) ->> 'email', ''))
  );
$fn$;
revoke all on function public.escala_is_member() from public, anon;
grant execute on function public.escala_is_member() to authenticated;

