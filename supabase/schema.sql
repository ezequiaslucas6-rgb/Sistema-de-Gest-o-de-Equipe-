-- Rodízio automático: substitui os plantões do setor no intervalo numa única transação
create or replace function public.escala_replace_on_call(p_sector public.escala_sector, p_from text, p_to text, p_shifts jsonb)
returns integer
language sql
security invoker
set search_path = ''
as $fn$
  delete from public.escala_on_call_shifts o
  using public.escala_teams t
  where t.id = o.team_id and t.sector = p_sector and o.weekend_start between p_from and p_to;

  insert into public.escala_on_call_shifts (team_id, weekend_start, comp_dates)
  select t.id, s->>'weekendStart', coalesce(s->'compDates', '[]'::jsonb)
  from jsonb_array_elements(p_shifts) s
  join public.escala_teams t on t.id = (s->>'teamId')::bigint and t.sector = p_sector;

  select count(*)::integer from public.escala_on_call_shifts o
  join public.escala_teams t on t.id = o.team_id
  where t.sector = p_sector and o.weekend_start between p_from and p_to;
$fn$;
revoke all on function public.escala_replace_on_call(public.escala_sector, text, text, jsonb) from public, anon;
grant execute on function public.escala_replace_on_call(public.escala_sector, text, text, jsonb) to authenticated;
